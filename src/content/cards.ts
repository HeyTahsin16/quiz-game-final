import type {CardDefinition, CardEffect} from '../engine/cards'

/**
 * Helper to scale numeric values in effects by +40% (rounded, at least +1 for positive magnitudes)
 * for standard upgrades.
 */
function scaleValue40(n: number): number {
	if (n === 0) return 0
	const sign = n < 0 ? -1 : 1
	const abs = Math.abs(n)
	const scaled = Math.max(abs + 1, Math.round(abs * 1.4))
	return sign * scaled
}

function upgradeEffectMagnitude(effect: CardEffect): CardEffect {
	switch (effect.type) {
		case 'damage':
			return {...effect, amount: scaleValue40(effect.amount)}
		case 'rampageDamage':
			return {
				...effect,
				base: scaleValue40(effect.base),
				increment: scaleValue40(effect.increment),
			}
		case 'block':
		case 'conditionalNoBlock':
		case 'heal':
		case 'nextTurnHeal':
		case 'raiseMaxHp':
			return {...effect, amount: scaleValue40(effect.amount)}
		case 'geneticHeal':
			return {
				...effect,
				base: scaleValue40(effect.base),
				increment: scaleValue40(effect.increment),
			}
		case 'regen':
			return {...effect, amount: scaleValue40(effect.amount)}
		case 'applyPower':
			return {...effect, amount: scaleValue40(effect.amount)}
		case 'banePoison':
			return {
				...effect,
				base: scaleValue40(effect.base),
				ifPoisoned: scaleValue40(effect.ifPoisoned),
			}
		default:
			return {...effect}
	}
}

function makeStandardMagnitudeUpgrade(
	upgradedText: string,
	customMapper?: (effects: CardEffect[]) => CardEffect[],
): (card: CardDefinition) => CardDefinition {
	return (card: CardDefinition) => ({
		...card,
		name: `${card.name}+`,
		upgraded: true,
		effects: customMapper ? customMapper(card.effects) : card.effects.map(upgradeEffectMagnitude),
		text: upgradedText,
	})
}

function makeCostReductionUpgrade(newCost?: number): (card: CardDefinition) => CardDefinition {
	return (card: CardDefinition) => ({
		...card,
		name: `${card.name}+`,
		upgraded: true,
		cost: newCost !== undefined ? newCost : Math.max(0, card.cost - 1),
	})
}

